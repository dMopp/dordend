namespace rummage::ui {

class XcursorFallback;

struct Modifiers {
    bool ctrl{false};
    bool shift{false};
    bool alt{false};
    bool super{false};

    bool operator==(const Modifiers&) const = default;
};

struct KeyEvent {
    xkb_keysym_t keysym{XKB_KEY_NoSymbol};
    std::string text;  // UTF-8 the key produces (after dead keys/compose); empty for e.g. arrows
    Modifiers modifiers{};
    bool repeat{false};  // generated by key repeat, not by the user pressing again
};

enum class PointerButton : std::uint8_t { left, right, middle, back, forward, other };

enum class CursorShape : std::uint8_t {
    standard,  // the arrow
    pointer,   // a hand, over something clickable
    text,
    wait,
    progress,
    grab,
    grabbing,
    not_allowed,
    ew_resize,  // column dividers
    ns_resize,
    // The window's edges and corners (client-side decorations).
    n_resize,
    s_resize,
    e_resize,
    w_resize,
    ne_resize,
    nw_resize,
    se_resize,
    sw_resize,
};

struct PointerEvent {
    enum class Kind : std::uint8_t { enter, leave, motion, press, release, scroll };

    Kind kind{Kind::motion};
    float x{0.0F};  // logical pixels, surface-local; valid for every kind except leave
    float y{0.0F};
    PointerButton button{PointerButton::other};  // press and release
    int click_count{0};    // press: 1, 2 for a double click, 3 for a triple click...
    float scroll_x{0.0F};  // scroll: surface pixels, positive = right / down
    float scroll_y{0.0F};
    float wheel_x{0.0F};  // scroll: wheel notches (fractional on high-resolution wheels), 0 if
    float wheel_y{0.0F};  // not a wheel
    bool scroll_finger{false};  // scroll from a touchpad: candidate for kinetic scrolling
    bool scroll_stop{false};    // the finger left the touchpad: start inertia now
    Modifiers modifiers{};
};

// Owner for xkbcommon handles, released by their unref function.
template <class T, void (*Unref)(T*)>
struct XkbDeleter {
    void operator()(T* handle) const noexcept { Unref(handle); }
};

template <class T, void (*Unref)(T*)>
using XkbPtr = std::unique_ptr<T, XkbDeleter<T, Unref>>;

// Input from the compositor's wl_seat: keyboard and pointer.
//
// The keymap is the compositor's (the user's layout as configured in Umbriel). Dead keys and
// compose sequences follow the locale's compose table. Key repeat uses the compositor's rate and
// delay through a timerfd watched by the event loop (attach()). Key presses reach the handler only
// while a rummage surface has keyboard focus.
//
// Pointer: clicks are counted (double, triple click) when presses of the same button land within
// the double-click time and a few pixels of each other; scroll axes are gathered per wl_pointer
// frame. The cursor shape is set through cursor-shape-v1 when the compositor offers it, else drawn
// from the xcursor theme (XcursorFallback); RUMMAGE_FORCE_XCURSOR=1 forces the latter, to try it
// on a compositor that has cursor-shape-v1.
//
// Must not outlive the Display. Not copyable or movable: listeners keep a pointer to it.
class Seat {
public:
    using KeyHandler = std::function<void(const KeyEvent& event)>;
    using PointerHandler = std::function<void(const PointerEvent& event)>;

    explicit Seat(Display& display);
    ~Seat();

    Seat(const Seat&) = delete;
    Seat& operator=(const Seat&) = delete;
    Seat(Seat&&) = delete;
    Seat& operator=(Seat&&) = delete;

    void set_key_handler(KeyHandler handler) { key_handler_ = std::move(handler); }

    void set_pointer_handler(PointerHandler handler) { pointer_handler_ = std::move(handler); }

    // Double-click window and slop (logical pixels). Wayland does not share the desktop's
    // setting, so it comes from rummage's config.
    void set_multi_click(std::chrono::milliseconds time, float slop) {
        multi_click_ms_ = static_cast<std::uint32_t>(time.count());
        multi_click_slop_ = slop;
    }

    // Cursor over rummage surfaces; applied at once if the pointer is inside one.
    void set_cursor(CursorShape shape);

    // The window's scale, for the xcursor fallback's images (cursor-shape-v1 needs none).
    void set_cursor_scale(double scale);

    // Hooks key repeat into the loop.
    void attach(core::EventLoop& loop);

    // The serial of the last key or button press: what xdg-activation tokens are tied to.
    [[nodiscard]] std::uint32_t input_serial() const noexcept { return input_serial_; }

    // The modifiers held now, as the compositor last told (a drag reads them as it moves).
    [[nodiscard]] Modifiers modifiers() const { return current_modifiers(); }

private:
    static void on_capabilities(void* data, wl_seat* seat, std::uint32_t capabilities);
    static void on_name(void* data, wl_seat* seat, const char* name);
    static void on_keymap(void* data, wl_keyboard* keyboard, std::uint32_t format, std::int32_t fd,
                          std::uint32_t size);
    static void on_keyboard_enter(void* data, wl_keyboard* keyboard, std::uint32_t serial,
                                  wl_surface* surface, wl_array* keys);
    static void on_keyboard_leave(void* data, wl_keyboard* keyboard, std::uint32_t serial,
                                  wl_surface* surface);
    static void on_key(void* data, wl_keyboard* keyboard, std::uint32_t serial, std::uint32_t time,
                       std::uint32_t key, std::uint32_t state);
    static void on_modifiers(void* data, wl_keyboard* keyboard, std::uint32_t serial,
                             std::uint32_t depressed, std::uint32_t latched, std::uint32_t locked,
                             std::uint32_t group);
    static void on_repeat_info(void* data, wl_keyboard* keyboard, std::int32_t rate,
                               std::int32_t delay);

    static void on_pointer_enter(void* data, wl_pointer* pointer, std::uint32_t serial,
                                 wl_surface* surface, wl_fixed_t x, wl_fixed_t y);
    static void on_pointer_leave(void* data, wl_pointer* pointer, std::uint32_t serial,
                                 wl_surface* surface);
    static void on_pointer_motion(void* data, wl_pointer* pointer, std::uint32_t time, wl_fixed_t x,
                                  wl_fixed_t y);
    static void on_pointer_button(void* data, wl_pointer* pointer, std::uint32_t serial,
                                  std::uint32_t time, std::uint32_t button, std::uint32_t state);
    static void on_pointer_axis(void* data, wl_pointer* pointer, std::uint32_t time,
                                std::uint32_t axis, wl_fixed_t value);
    static void on_pointer_frame(void* data, wl_pointer* pointer);
    static void on_pointer_axis_source(void* data, wl_pointer* pointer, std::uint32_t source);
    static void on_pointer_axis_stop(void* data, wl_pointer* pointer, std::uint32_t time,
                                     std::uint32_t axis);
    static void on_pointer_axis_discrete(void* data, wl_pointer* pointer, std::uint32_t axis,
                                         std::int32_t discrete);
    static void on_pointer_axis_value120(void* data, wl_pointer* pointer, std::uint32_t axis,
                                         std::int32_t value120);

    void emit_pointer(PointerEvent event);
    void apply_cursor();
    void dispatch_repeat();
    void press(xkb_keycode_t keycode, bool repeat);
    void arm_repeat(xkb_keycode_t keycode);
    void disarm_repeat();
    [[nodiscard]] Modifiers current_modifiers() const;

    KeyHandler key_handler_;
    std::int32_t repeat_rate_{25};    // keys per second; 0 = no repeat
    std::int32_t repeat_delay_{600};  // milliseconds
    xkb_keycode_t repeat_key_{0};     // 0 = nothing repeating
    int repeat_fd_{-1};

    XkbPtr<xkb_context, xkb_context_unref> context_;
    XkbPtr<xkb_keymap, xkb_keymap_unref> keymap_;
    XkbPtr<xkb_state, xkb_state_unref> state_;
    XkbPtr<xkb_compose_table, xkb_compose_table_unref> compose_table_;
    XkbPtr<xkb_compose_state, xkb_compose_state_unref> compose_state_;

    // Scroll gathered until wl_pointer.frame.
    struct PendingScroll {
        bool any{false};
        float x{0.0F};
        float y{0.0F};
        float wheel_x{0.0F};
        float wheel_y{0.0F};
        bool finger{false};
        bool stop{false};
    };

    // Last press, for click counting.
    struct LastPress {
        PointerButton button{PointerButton::other};
        std::uint32_t time_ms{0};
        float x{0.0F};
        float y{0.0F};
        int count{0};
    };

    Display& display_;
    PointerHandler pointer_handler_;
    float pointer_x_{0.0F};
    float pointer_y_{0.0F};
    bool pointer_inside_{false};
    std::uint32_t pointer_enter_serial_{0};
    std::uint32_t input_serial_{0};
    CursorShape cursor_{CursorShape::standard};
    PendingScroll pending_scroll_;
    LastPress last_press_;
    std::uint32_t multi_click_ms_{400};
    float multi_click_slop_{4.0F};
    double cursor_scale_{1.0};
    std::unique_ptr<XcursorFallback> xcursor_;  // without cursor-shape-v1

    // Reverse order = teardown order: cursor device before the pointer it belongs to.
    WlPtr<wl_keyboard> keyboard_;  // the wl_seat itself belongs to the Display
    WlPtr<wl_pointer> pointer_;
    WlPtr<wp_cursor_shape_device_v1> cursor_device_;
};

}  // namespace rummage::ui
